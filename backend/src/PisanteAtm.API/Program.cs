// â”€â”€â”€ Auto-migrate & seed â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€
using (var scope = app.Services.CreateScope())
{
    var db = scope.ServiceProvider.GetRequiredService<AppDbContext>();
    await db.Database.MigrateAsync();

    var roleManager = scope.ServiceProvider.GetRequiredService<RoleManager<IdentityRole<Guid>>>();
    var userManager = scope.ServiceProvider.GetRequiredService<UserManager<AppUser>>();
    await SeedDataAsync(roleManager, userManager, scope.ServiceProvider.GetRequiredService<Microsoft.Extensions.Logging.ILogger<Program>>());
}

await app.RunAsync();

static async Task SeedDataAsync(
    RoleManager<IdentityRole<Guid>> roleManager,
    UserManager<AppUser> userManager,
    Microsoft.Extensions.Logging.ILogger logger)
{
    string[] roles = ["Admin", "Employee", "Customer"];
    foreach (var role in roles)
    {
        if (!await roleManager.RoleExistsAsync(role))
            await roleManager.CreateAsync(new IdentityRole<Guid>(role));
    }

    const string adminEmail = "admin@pisanteatm.com.br";
    if (await userManager.FindByEmailAsync(adminEmail) == null)
    {
        var admin = new AppUser
        {
            FirstName = "Admin",
            LastName = "Pisante ATM",
            Email = adminEmail,
            UserName = adminEmail,
            EmailConfirmed = true
        };
        var result = await userManager.CreateAsync(admin, "Admin@123456");
        if (result.Succeeded)
        {
            await userManager.AddToRoleAsync(admin, "Admin");
            logger.LogInformation("Admin user created: {Email}", adminEmail);
        }
    }
}



